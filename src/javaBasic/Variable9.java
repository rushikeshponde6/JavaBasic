package javaBasic;

public class Variable9 {
    public static void main(String[] args) {
        int a;   //Declaring a local variable
        a=6;  // Assigning value to a variable
        System.out.println(a);   //6-  Calling a variable

        char b = 'p';
        System.out.println(b);    //p

        String c = "w";
        System.out.println(c);    //w

        String d = "Hello Selenium";
        System.out.println(d);     //Hello Selenium
    }
}
