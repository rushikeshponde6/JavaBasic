package javaLoops;

public class IfElse3 {
    public static void main(String[] args) {
        int p=400;
        int q=300;

        if(p<q){
            System.out.println("p is lesser than q");
        }else if(p==q){
            System.out.println("p is equl to q");
        }else{
            System.out.println("p is grater than q");
        }
    }
}
